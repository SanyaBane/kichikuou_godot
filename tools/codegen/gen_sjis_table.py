"""Generate src/Kichikuou.Content/Text/SjisTable.g.cs from xsys35c 1.13.0's common/s2utbl.h.

The import decodes the game's Shift JIS with xsys35c's own table, not a platform's code page 932, so its
text is what xsys35dc 1.13 writes (docs/import.md, step 5). s2utbl.h is the table s2u[lead - 0x80][trail
- 0x40]: 128 pointers to rows (s2u_80 .. s2u_ff) of 192 code points, 0 where a pair maps to nothing. It is not part of
the repository; get it from https://github.com/kichikuou/xsys35c (tag v1.13.0, common/s2utbl.h).

    python tools/codegen/gen_sjis_table.py <s2utbl.h>            # writes the .g.cs
    python tools/codegen/gen_sjis_table.py <s2utbl.h> --check    # fails if it differs
"""
import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "src" / "Kichikuou.Content" / "Text" / "SjisTable.g.cs"
ROWS, COLUMNS = 128, 192

HEADER = """\
// <auto-generated> by tools/codegen/gen_sjis_table.py from xsys35c 1.13.0 (https://github.com/kichikuou/xsys35c),
// common/s2utbl.h: Copyright (C) 2020 <KichikuouChrome@gmail.com>. GNU General Public License, version 2 or
// later, as KichikuouGodot (LICENSE). Do not edit by hand; re-run the generator. </auto-generated>

namespace Kichikuou.Content.Text;

public static partial class Sjis
{
    /// <summary>xsys35c's <c>s2u</c>: the code point of the pair (lead, trail) at (lead - 0x80) * 192 + trail - 0x40, 0 for none.</summary>
    private static ReadOnlySpan<ushort> Table =>
    [
"""

FOOTER = """\
    ];
}
"""


def parse(text: str) -> list[int]:
    rows = {}
    for m in re.finditer(r"static const uint16_t s2u_([0-9a-f]{2})\[\]\s*=\s*\{(.*?)\};", text, re.S):
        values = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{4})", m.group(2))]
        if len(values) != COLUMNS:
            sys.exit(f"s2u_{m.group(1)} has {len(values)} entries, not {COLUMNS}")
        rows[int(m.group(1), 16)] = values
    top = re.search(r"static const uint16_t \*s2u\[\]\s*=\s*\{(.*?)\};", text, re.S)
    if not top:
        sys.exit("no s2u[] table")
    # Each lead byte's row is the one s2u[] points to (the half-width range 0xa0-0xdf points to the empty s2u_80).
    order = [int(n, 16) for n in re.findall(r"s2u_([0-9a-f]{2})", top.group(1))]
    if len(order) != ROWS:
        sys.exit(f"s2u[] has {len(order)} rows, not {ROWS}")
    return [v for row in order for v in rows[row]]


def render(table: list[int]) -> str:
    lines = []
    for row in range(ROWS):
        lines.append(f"        // 0x{0x80 + row:02X}")
        values = table[row * COLUMNS:(row + 1) * COLUMNS]
        for i in range(0, COLUMNS, 16):
            lines.append("        " + " ".join(f"0x{v:04X}," for v in values[i:i + 16]))
    return HEADER + "\n".join(lines) + "\n" + FOOTER


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("header", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = render(parse(args.header.read_text(encoding="ascii")))
    if args.check:
        if OUT.read_text(encoding="utf-8") != source:
            sys.exit(f"{OUT} differs from {args.header}")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(source, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
