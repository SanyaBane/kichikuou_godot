def var_name(n: int) -> str:
    return f"VAR{n:04d}"


def load_dict() -> dict[int, dict[str, str]]:
    with open(DICT, encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    return {int(r["var"][3:]): r for r in rows}


def ident(entry: dict[str, str], n: int) -> str:
    return entry["name"].strip() or var_name(n)


def doc(entry: dict[str, str], n: int, indent: str) -> str:
    conf = entry["confidence"] or "?"
    meaning = escape(entry["meaning"] or "Unknown.")
    return f"{indent}/// <summary>{var_name(n)} [{conf}] — {meaning}</summary>\n"


def field_name(entry: dict[str, str], n: int, prefix: str) -> str:
    name = ident(entry, n)
    if name.startswith(prefix) and len(name) > len(prefix):
        rest = name[len(prefix):]
        return rest if rest[0].isalpha() else name
    return name


def generate() -> str:
    d = load_dict()
    if len(d) != 806:
        sys.exit(f"expected 806 variables in {DICT}, found {len(d)}")

    bound = {}
    for t in TABLES:
        for f in t.fields:
            bound[f] = t
        for _, fields in t.aliases:
            for f in fields:
                bound[f] = t

    out = []
    w = out.append
    w("// <auto-generated>\n")
    w("// Generated by tools/codegen/gen_state.py from docs/variables.tsv. Do not edit by hand.\n")
    w("// </auto-generated>\n")
    w("using Kichikuou.Core.Sys3;\n\n")
    w("namespace Kichikuou.Core.State;\n\n")

    w("public sealed partial class GameState\n{\n")
    w("    private static void AllocatePages(ScriptMemory memory)\n    {\n")
    for page, maxindex in PAGES.items():
        w(f"        memory.AllocatePage({page}, {maxindex + 1});\n")
    w("    }\n\n")

    for n in range(806):
        if n in bound:
            continue
        e = d[n]
        w(doc(e, n, "    "))
        w(f"    public ref Sys3Int {ident(e, n)} => ref Memory.Var({n});\n\n")

    for t in TABLES:
        cur = ident(d[t.cursor], t.cursor)
        w(f"    /// <summary>Records on page {t.page} indexed by <see cref=\"{cur}\"/> "
          f"(bound in {t.source}).</summary>\n")
        w(f"    public RecordTable<{t.type}> {t.prop} => new(Memory, {t.count});\n\n")
    w("}\n")

    for t in TABLES:
        cur = ident(d[t.cursor], t.cursor)
        alias_note = ""
        if t.aliases:
            alias_note = " Also addressed through " + ", ".join(
                f"<c>{ident(d[c], c)}</c> ({', '.join(ident(d[f], f) for f in fs)})" for c, fs in t.aliases) + "."
        w(f"\n/// <summary>One record of <see cref=\"GameState.{t.prop}\"/>: page {t.page}, "
          f"<c>{t.count}</c> slots per field from offset {t.base}; the script selects it with "
          f"<c>{cur}</c>.{alias_note}</summary>\n")
        w(f"public sealed class {t.type}(ScriptMemory memory, int index) : IRecord<{t.type}>\n{{\n")
        w(f"    /// <inheritdoc />\n    public static {t.type} Create(ScriptMemory memory, int index) => new(memory, index);\n\n")
        w("    /// <summary>The cursor value that selects this record.</summary>\n")
        w("    public int Index => index;\n")
        for k, f in enumerate(t.fields):
            e = d[f]
            offset = t.base + t.count * k
            w("\n" + doc(e, f, "    "))
            w(f"    public Sys3Int {field_name(e, f, t.prefix)}\n    {{\n"
              f"        get => memory.ReadPage({t.page}, {offset} + index);\n"
              f"        set => memory.WritePage({t.page}, {offset} + index, value);\n    }}\n")
        w("}\n")
    return "".join(out)


def cs_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate_catalog() -> str:
    """Names, groups and page bindings, for reports that compare memory (golden tests)."""
    d = load_dict()
    out = []
    w = out.append
    w("// <auto-generated>\n")
    w("// Generated by tools/codegen/gen_state.py from docs/variables.tsv. Do not edit by hand.\n")
    w("// </auto-generated>\n")
    w("namespace Kichikuou.Core.State;\n\n")
    w("public static partial class VariableCatalog\n{\n")
    w("    private static readonly VariableInfo[] VariableTable =\n    [\n")
    for n in range(806):
        e = d[n]
        w(f"        new({cs_string(ident(e, n))}, {cs_string(e['group'].strip())}),\n")
    w("    ];\n\n")
    w("    private static readonly PageBinding[] BindingTable =\n    [\n")
    for t in TABLES:
        for cursor, fields in [(t.cursor, t.fields)] + t.aliases:
            for k, f in enumerate(fields):
                w(f"        new({f}, {t.page}, {t.base + t.count * k}, {t.count}, {cursor}, "
                  f"{cs_string(t.prop)}, {cs_string(field_name(d[f], f, t.prefix))}),\n")
    w("    ];\n\n")
    w("    private static readonly (int Page, int Size)[] PageTable =\n    [\n")
    for page, maxindex in PAGES.items():
        w(f"        ({page}, {maxindex + 1}),\n")
    w("    ];\n}\n")
    return "".join(out)


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(generate(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    CATALOG.write_text(generate_catalog(), encoding="utf-8", newline="\n")
    print(f"wrote {CATALOG.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
